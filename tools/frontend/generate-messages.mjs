import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const catalogsDir = new URL('../../internal/i18n/catalogs/', import.meta.url);
const generated = new URL('../../internal/ui/src/core/messages.generated.ts', import.meta.url);
const defaultLocale = 'zh-Hans';
const locales = readdirSync(catalogsDir)
  .filter((name) => name.endsWith('.json'))
  .map((name) => name.slice(0, -5));

const readCatalog = (locale) =>
  JSON.parse(readFileSync(new URL(locale + '.json', catalogsDir), 'utf8'));

function names(message) {
  return [...new Set(Array.from(message.matchAll(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g), (part) => part[1]))].sort();
}

function spreadsheetErrors(message) {
  return [...new Set(message.match(/#(?:DIV\/0!|REF!|VALUE!|NUM!|NAME\?|N\/A|NULL!|CALC!|SPILL!)/g) ?? [])].sort();
}

const source = readCatalog(defaultLocale);
const keys = Object.keys(source).sort();
const parameters = new Map();
for (const key of keys) {
  if (!/^[a-z][a-zA-Z0-9]*(?:\.[a-z][a-zA-Z0-9]*)+$/.test(key)) {
    throw new Error('Invalid message ID: ' + key);
  }
  if (typeof source[key] !== 'string' || !source[key].trim()) {
    throw new Error(defaultLocale + ': empty message ' + key);
  }
  parameters.set(key, names(source[key]));
}
for (const locale of locales) {
  const catalog = readCatalog(locale);
  for (const key of new Set([...keys, ...Object.keys(catalog)])) {
    if (typeof catalog[key] !== 'string' || !catalog[key].trim() || !parameters.has(key)) {
      throw new Error(locale + ': missing or unknown message ' + key);
    }
    if (names(catalog[key]).join(',') !== parameters.get(key).join(',')) {
      throw new Error(locale + ': parameter mismatch for ' + key);
    }
    if (spreadsheetErrors(catalog[key]).join(',') !== spreadsheetErrors(source[key]).join(',')) {
      throw new Error(locale + ': spreadsheet error token mismatch for ' + key);
    }
  }
}

for (const page of ['index.html', 'storage-recovery.html']) {
  const html = readFileSync(new URL('../../internal/ui/web/' + page, import.meta.url), 'utf8');
  for (const match of html.matchAll(/\{\{\.T \x60([^\x60]+)\x60\}\}/g)) {
    const key = match[1];
    const args = parameters.get(key);
    if (!args || args.length) throw new Error(page + ': invalid static message ' + key);
  }
}

const entries = keys.filter((key) => key.startsWith('ui.')).map((key) => {
  const args = parameters.get(key);
  const tuple = args.length ? '[values: { ' + args.map((name) => name + ': unknown').join('; ') + ' }]' : '[]';
  return "  '" + key + "': " + tuple + ';';
});
const expected = [
  '// Generated by tools/frontend/generate-messages.mjs. DO NOT EDIT.',
  'export interface MessageArguments {',
  ...entries,
  '}',
  '',
  'export type MessageKey = keyof MessageArguments;',
  '',
].join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(generated, 'utf8') !== expected) {
    throw new Error('Message types are stale. Run npm run generate:messages.');
  }
  console.log('PASS: ' + locales.length + ' catalogs, ' + keys.length + ' messages and named parameter sets');
} else {
  writeFileSync(generated, expected);
}
