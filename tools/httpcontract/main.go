// Command httpcontract generates browser wire types from the Go handlers' JSON structs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"slices"
	"sort"
	"strings"

	"excellens/internal/server"
	"excellens/internal/workbook"
)

const output = "internal/ui/src/contracts/http-wire.generated.ts"

var roots = map[reflect.Type]string{
	reflect.TypeFor[server.OpenedWorkbookResponse](): "OpenedWorkbookWire",
	reflect.TypeFor[server.ClosedWorkbookResponse](): "ClosedWorkbookWire",
	reflect.TypeFor[server.StylesResponse]():         "StylesWire",
	reflect.TypeFor[server.CompactRow]():             "CompactRowWire",
	reflect.TypeFor[workbook.RowData]():              "PlainRowWire",
	reflect.TypeFor[server.ViewportHeader]():         "ViewportHeaderWire",
	reflect.TypeFor[server.PreviewHeader]():          "PreviewHeaderWire",
}

type schema struct {
	names       map[reflect.Type]string
	definitions map[string]string
}

func (s *schema) expression(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Pointer:
		return s.expression(t.Elem()) + " | null"
	case reflect.Slice:
		elem := s.expression(t.Elem())
		if strings.Contains(elem, " | ") {
			elem = "(" + elem + ")"
		}
		return "readonly " + elem + "[] | null"
	case reflect.Struct:
		if name, ok := s.names[t]; ok {
			return name
		}
		name := roots[t]
		if name == "" {
			name = t.Name() + "Wire"
		}
		if _, exists := s.definitions[name]; exists {
			panic("duplicate wire type name: " + name)
		}
		s.names[t] = name
		s.definitions[name] = ""
		var fields strings.Builder
		var parents []string
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			if !f.IsExported() {
				continue
			}
			tag := strings.Split(f.Tag.Get("json"), ",")
			key := tag[0]
			if key == "-" {
				continue
			}
			if f.Anonymous && key == "" {
				if f.Type.Kind() != reflect.Struct {
					panic("unsupported embedded field: " + f.Name)
				}
				parents = append(parents, s.expression(f.Type))
				continue
			}
			if key == "" {
				key = f.Name
			}
			optional := ""
			kind := s.expression(f.Type)
			for _, option := range tag[1:] {
				switch option {
				case "omitempty", "omitzero":
					optional = "?"
					kind = strings.TrimSuffix(kind, " | null")
				case "":
				default:
					panic("unsupported JSON option: " + option)
				}
			}
			fmt.Fprintf(&fields, "  readonly %s%s: %s;\n", key, optional, kind)
		}
		var out strings.Builder
		if _, isRoot := roots[t]; isRoot {
			fmt.Fprintf(&out, "/** @httpResponse %s */\n", name)
		}
		out.WriteString("export interface " + name)
		if len(parents) > 0 {
			out.WriteString(" extends " + strings.Join(parents, ", "))
		}
		out.WriteString(" {\n" + fields.String() + "}")
		s.definitions[name] = out.String()
		return name
	}
	panic("unsupported JSON field: " + t.String())
}
func generate() []byte {
	s := schema{names: map[reflect.Type]string{}, definitions: map[string]string{}}
	for root := range roots {
		s.expression(root)
	}
	sections := make([]string, 0, len(s.definitions))
	for name := range s.definitions {
		sections = append(sections, name)
	}
	sort.Strings(sections)
	lines := []string{"// Generated by go run ./tools/httpcontract. Source: Go JSON response structs."}
	for _, name := range sections {
		lines = append(lines, s.definitions[name])
	}
	return []byte(strings.Join(lines, "\n\n") + "\n")
}
func main() {
	check := flag.Bool("check", false, "check the generated wire types")
	flag.Parse()
	want := generate()
	var err error
	if *check {
		var got []byte
		got, err = os.ReadFile(output)
		if err == nil && !slices.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
			err = fmt.Errorf("stale %s; run go run ./tools/httpcontract", output)
		}
	} else {
		err = os.WriteFile(output, want, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
